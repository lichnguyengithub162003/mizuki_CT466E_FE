function item(
  id: number,
  name: string,
  _brandId: number | null,
  brandName: string | null,
  quantity = 1,
  prices: { original?: number; promotional?: number; final?: number } = {},
): CustomerOrderItem {
  const promotional = prices.promotional ?? 180_000;
  const final = prices.final ?? promotional;
  return {
    id,
    productVariantId: 10_000 + id,
    productName: name,
    brandId: null,
    brandName,
    imageUrl: PREVIEW_PRODUCT_IMAGES[id % PREVIEW_PRODUCT_IMAGES.length],
    quantity,
    originalPrice: prices.original ?? null,
    promotionalPrice: promotional,
    finalUnitPrice: final,
    unitPrice: promotional,
    lineTotal: final * quantity,
    canReview: false,
    review: null,
  };
}

